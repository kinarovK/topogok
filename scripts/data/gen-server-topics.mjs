// Writes server/topics.generated.ts: the feature ids of every topic package in public/data, so the
// API can rebuild a round (startGame / reduce) without parsing GeoJSON per request (10 ms CPU limit).
// Usage: node scripts/data/gen-server-topics.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dataDir = join(root, 'public/data');
const out = join(root, 'server/topics.generated.ts');
const topics = {};
for (const topic of readdirSync(dataDir).sort()) {
  for (const version of readdirSync(join(dataDir, topic)).sort()) {
    const regions = join(dataDir, topic, version, 'regions.geojson');
    if (!existsSync(regions)) continue;
    const ids = JSON.parse(readFileSync(regions, 'utf8')).features.map((f) => f.id).sort();
    (topics[topic] ??= {})[version] = ids;
  }
}
const text = `// Generated by scripts/data/gen-server-topics.mjs from public/data. Do not edit.\nexport const TOPIC_FEATURES: Record<string, Record<string, readonly string[]>> = ${JSON.stringify(topics, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) { console.error('FAIL: server/topics.generated.ts is stale; run node scripts/data/gen-server-topics.mjs'); process.exit(1); }
  console.log('OK: server/topics.generated.ts matches public/data');
} else {
  writeFileSync(out, text);
  console.log(`Wrote ${out}`);
}
